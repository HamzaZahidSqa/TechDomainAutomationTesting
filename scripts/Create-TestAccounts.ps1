<#
.SYNOPSIS
  Creates Tech Domain test accounts for every role using Mailinator inboxes.

.DESCRIPTION
  Roles:
    1. Individual Engineer  - POST auth/signup (FREELANCER)            + OTP
    2. Vendor               - POST auth/signup with freelanceCompanyName + OTP
    3. Customer             - POST auth/signup with customerCompanyName  + OTP
    4. Vendor Engineer      - POST freelanceCompany/createEngineer (as Vendor)
    5. Customer User        - POST customerUsers/createUser (as Customer); password is emailed

  Works non-interactively in two steps:
    Step 1 (no OTP params): signs up roles 1-3; OTPs go to the Mailinator inboxes.
    Step 2 (-Suffix + OTPs): verifies the OTPs, then creates roles 4-5.
  The password is generated in step 1 and re-read from test-accounts.json in step 2.
  Keep test-accounts.json out of git.

.EXAMPLE
  .\scripts\Create-TestAccounts.ps1
  .\scripts\Create-TestAccounts.ps1 -Suffix 10090955 -EngineerOtp 123456 -VendorOtp 234567 -CustomerOtp 345678
  .\scripts\Create-TestAccounts.ps1 -Suffix 10090955 -ResendOtp
#>
param(
    [string]$BaseUrl = 'https://api.dev.techdomain.com.au/api',

    # Makes emails unique per run, e.g. vendor-10091530@mailinator.com. Pass the step-1 value in step 2.
    [string]$Suffix = (Get-Date -Format 'MMddHHmm'),

    [string]$EngineerOtp,
    [string]$VendorOtp,
    [string]$CustomerOtp,

    # Re-sends OTPs for roles 1-3 (use when they have expired)
    [switch]$ResendOtp,

    [string]$Phone = '+61412345678'
)

$ErrorActionPreference = 'Stop'
$BaseUrl = $BaseUrl.TrimEnd('/')
$outFile = Join-Path (Split-Path $PSScriptRoot -Parent) 'test-accounts.json'
$isStep2 = [bool]($EngineerOtp -or $VendorOtp -or $CustomerOtp)

function Invoke-Api {
    param([string]$Method, [string]$Path, $Body, [string]$Token)
    $headers = @{ Origin = 'https://dev.techdomain.com.au' }
    if ($Token) { $headers['Authorization'] = "Bearer $Token" }
    $params = @{
        Method      = $Method
        Uri         = "$BaseUrl/$Path"
        Headers     = $headers
        ContentType = 'application/json'
    }
    if ($null -ne $Body) { $params['Body'] = ($Body | ConvertTo-Json -Depth 5) }
    try {
        return Invoke-RestMethod @params
    } catch {
        $msg = $_.ErrorDetails.Message
        if (-not $msg) { $msg = $_.Exception.Message }
        throw "$Method $Path failed: $msg"
    }
}

function Get-Inbox([string]$email) {
    return "https://www.mailinator.com/v4/public/inboxes.jsp?to=$($email.Split('@')[0])"
}

$emails = [ordered]@{
    engineer       = "individualengineer-$Suffix@mailinator.com"
    vendor         = "vendor-$Suffix@mailinator.com"
    customer       = "customer-$Suffix@mailinator.com"
    vendorEngineer = "vendorengineer-$Suffix@mailinator.com"
    customerUser   = "customeruser-$Suffix@mailinator.com"
}

# Password: reuse the one saved for this suffix, otherwise generate one
$plainPassword = $null
if (Test-Path $outFile) {
    $saved = @(Get-Content $outFile -Raw | ConvertFrom-Json) |
        Where-Object { $_.email -like "*-$Suffix@*" -and $_.password -and $_.password -ne 'see inbox' } |
        Select-Object -First 1
    if ($saved) { $plainPassword = $saved.password }
}
if (-not $plainPassword) {
    if ($isStep2 -or $ResendOtp) { throw "No saved password for suffix $Suffix in $outFile" }
    # 12 chars: guaranteed upper, lower, digit and one of !@#$%^&* (backend rule)
    $rand = New-Object System.Random
    $pick = { param($set, $n) -join (1..$n | ForEach-Object { $set[$rand.Next($set.Length)] }) }
    $chars = (& $pick 'ABCDEFGHJKLMNPQRSTUVWXYZ' 3) + (& $pick 'abcdefghijkmnpqrstuvwxyz' 5) + (& $pick '23456789' 3) + (& $pick '!@#$%^&*' 1)
    $plainPassword = -join ($chars.ToCharArray() | Sort-Object { $rand.Next() })
    Write-Host 'Generated a password (saved in test-accounts.json).'
}

$results = @()
function Add-Result($role, $email, $status, $note) {
    # Customer User password is generated by the server and emailed
    $pw = $plainPassword
    if ($role -eq 'Customer User') { $pw = 'see inbox' }
    $script:results += [pscustomobject]@{ role = $role; email = $email; password = $pw; status = $status; note = $note; inbox = (Get-Inbox $email) }
    $color = 'Green'
    if ($status -in 'failed', 'skipped') { $color = 'Red' }
    if ($status -eq 'otp-pending') { $color = 'Yellow' }
    Write-Host "  -> $status $note" -ForegroundColor $color
}

function Get-Token([string]$email) {
    return (Invoke-Api POST 'auth/login' @{ email = $email; password = $plainPassword }).accessToken
}

$signupRoles = @(
    @{ key = 'engineer'; role = 'Individual Engineer'; otp = $EngineerOtp; extra = @{ firstName = 'Individual'; lastName = 'Engineer' } }
    @{ key = 'vendor';   role = 'Vendor';              otp = $VendorOtp;   extra = @{ firstName = 'Vendor'; lastName = 'Owner'; freelanceCompanyName = "Vendor Company $Suffix" } }
    @{ key = 'customer'; role = 'Customer';            otp = $CustomerOtp; extra = @{ firstName = 'Customer'; lastName = 'Owner'; customerCompanyName = "Customer Company $Suffix"; companyAnnualRevenue = '1' } }
)

if ($ResendOtp) {
    foreach ($r in $signupRoles) {
        $email = $emails[$r.key]
        Write-Host "`nResend OTP: $email"
        try { Invoke-Api GET "otps/resend/$email" | Out-Null; Write-Host "  -> sent. Open: $(Get-Inbox $email)" -ForegroundColor Yellow }
        catch { Write-Host "  -> $($_.Exception.Message)" -ForegroundColor Red }
    }
    return
}

$tokens = @{}
$i = 0
foreach ($r in $signupRoles) {
    $i++
    $email = $emails[$r.key]
    Write-Host "`n[$i/5] $($r.role): $email"
    try {
        if (-not $isStep2) {
            $body = @{ email = $email; phoneNumber = $Phone; password = $plainPassword; referralSource = 'LinkedIn'; address = @{} } + $r.extra
            Invoke-Api POST 'auth/signup' $body | Out-Null
            Add-Result $r.role $email 'otp-pending' "OTP in $(Get-Inbox $email)"
            continue
        }
        if ($r.otp) { Invoke-Api POST 'otps/verify' @{ email = $email; code = $r.otp.Trim() } | Out-Null }
        $tokens[$r.key] = Get-Token $email
        Add-Result $r.role $email 'created' ''
    } catch { Add-Result $r.role $email 'failed' $_.Exception.Message }
}

if ($isStep2) {
    # 4. Vendor Engineer (created by the vendor)
    Write-Host "`n[4/5] Vendor Engineer: $($emails.vendorEngineer)"
    if ($tokens['vendor']) {
        try {
            Invoke-Api POST 'freelanceCompany/createEngineer' @{ firstName = 'Vendor'; lastName = 'Engineer'; email = $emails.vendorEngineer; phoneNumber = $Phone; password = $plainPassword } $tokens['vendor'] | Out-Null
            Add-Result 'Vendor Engineer' $emails.vendorEngineer 'created' 'linked to vendor'
        } catch { Add-Result 'Vendor Engineer' $emails.vendorEngineer 'failed' $_.Exception.Message }
    } else { Add-Result 'Vendor Engineer' $emails.vendorEngineer 'skipped' 'vendor not verified/logged in' }

    # 5. Customer User (created by the customer; random password is emailed)
    Write-Host "`n[5/5] Customer User: $($emails.customerUser)"
    if ($tokens['customer']) {
        try {
            Invoke-Api POST 'customerUsers/createUser' @{ firstName = 'Customer'; lastName = 'User'; email = $emails.customerUser; phoneNumber = $Phone } $tokens['customer'] | Out-Null
            Add-Result 'Customer User' $emails.customerUser 'created' 'password emailed to inbox'
        } catch { Add-Result 'Customer User' $emails.customerUser 'failed' $_.Exception.Message }
    } else { Add-Result 'Customer User' $emails.customerUser 'skipped' 'customer not verified/logged in' }
} else {
    Write-Host "`nNext: copy the 3 OTPs from the inboxes above, then run:" -ForegroundColor Cyan
    Write-Host "  .\scripts\Create-TestAccounts.ps1 -Suffix $Suffix -EngineerOtp <otp> -VendorOtp <otp> -CustomerOtp <otp>" -ForegroundColor Cyan
}

$results | ConvertTo-Json | Out-File -FilePath $outFile -Encoding utf8
Write-Host "`nSaved: $outFile"
$results | Format-Table role, email, status, note -AutoSize
